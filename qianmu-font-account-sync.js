import { createConfiguredStAccountStorage, isStAccountStorageConfigured } from './qianmu-st-account-storage.js';
import { normalizeFontLibrary, mergeFontLibraryRecords } from './qianmu-font-library-state.js';

// The directory is deliberately a small metadata document.  Font bytes do not
// belong in the mutable catalog: when the user explicitly opts in, each file is
// retained as a content-addressed immutable account document instead.
export const FONT_ACCOUNT_SYNC_SLOT = 'font-library';
export const FONT_ACCOUNT_SYNC_VERSION = 1;
const ASSET_PREFIX = 'fontasset-';
const ASSET_MAX_BYTES = 48 * 1024 * 1024;
const plain = value => value && typeof value === 'object' && !Array.isArray(value)
  && [Object.prototype, null].includes(Object.getPrototypeOf(value));
const uniqueId = () => `f_${globalThis.crypto?.randomUUID?.().replaceAll('-', '') || `${Date.now()}_${Math.random().toString(36).slice(2)}`}`;

function encode(bytes) {
  const input = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  if (typeof btoa === 'function') {
    let binary = '';
    for (let at = 0; at < input.length; at += 32768) binary += String.fromCharCode(...input.subarray(at, at + 32768));
    return btoa(binary);
  }
  return Buffer.from(input).toString('base64');
}

function decode(value) {
  if (typeof value !== 'string' || value.length > Math.ceil(32 * 1024 * 1024 / 3) * 4
    || value.length % 4 || !/^[A-Za-z0-9+/]*={0,2}$/.test(value)) throw new Error('字体原件编码无效或过大');
  if (typeof atob === 'function') return Uint8Array.from(atob(value), character => character.charCodeAt(0));
  return new Uint8Array(Buffer.from(value, 'base64'));
}

function assetSlot(id) {
  // Local IDs are generated by the font library and are already collision
  // resistant. Keeping the same prefix on every device makes references stable.
  return `${ASSET_PREFIX}${String(id).replace(/[^a-zA-Z0-9-]/g, '-').slice(0, 80)}`;
}

function stateWithoutPreference(value) {
  const state = normalizeFontLibrary(value);
  const { syncLocalOriginals: _ignored, ...catalog } = state;
  return catalog;
}

function catalogValue(value) {
  if (!plain(value) || value.version !== FONT_ACCOUNT_SYNC_VERSION || !plain(value.library)) {
    throw new Error('字体账户目录格式无效，未覆盖本机字体');
  }
  const library = normalizeFontLibrary(value.library);
  const originals = plain(value.originals) ? value.originals : {};
  for (const [id, reference] of Object.entries(originals)) {
    if (!/^[a-zA-Z0-9_-]{1,96}$/.test(id) || !plain(reference)
      || typeof reference.slot !== 'string' || !reference.slot.startsWith(ASSET_PREFIX)
      || !Number.isSafeInteger(reference.bytes) || reference.bytes < 1 || reference.bytes > ASSET_MAX_BYTES
      || typeof reference.fingerprint !== 'string' || !/^[a-f0-9]{64}$/.test(reference.fingerprint)) {
      throw new Error('字体账户目录中的原件引用无效');
    }
  }
  return { library, originals };
}

export function createFontAccountSync({ storageFactory = createConfiguredStAccountStorage } = {}) {
  let storage = null;
  let disabled = false;
  let fingerprint = null;

  function ensureStorage() {
    if (disabled) return null;
    if (storage) return storage;
    if (!isStAccountStorageConfigured() && storageFactory === createConfiguredStAccountStorage) return null;
    try { storage = storageFactory({ maxBytes: ASSET_MAX_BYTES }); return storage; }
    catch { disabled = true; return null; }
  }

  async function readCatalog() {
    const current = ensureStorage();
    if (!current) return { value: null, fingerprint: null };
    const result = await current.read(FONT_ACCOUNT_SYNC_SLOT);
    if (!result?.exists) { fingerprint = null; return { value: null, fingerprint: null }; }
    const value = catalogValue(result.value);
    fingerprint = result.fingerprint;
    return { value, fingerprint };
  }

  async function writeCatalog(value, expectedFingerprint) {
    const current = ensureStorage();
    if (!current) return null;
    const result = await current.write(FONT_ACCOUNT_SYNC_SLOT, value, { expectedFingerprint });
    fingerprint = result?.fingerprint ?? fingerprint;
    return result;
  }

  async function preserveOriginal(font, localStore, originals) {
    if (!localStore?.get || !font || font.source?.kind !== 'local') return;
    const blob = await localStore.get(font.id);
    if (!blob?.size) return;
    if (blob.size > 32 * 1024 * 1024) throw new Error(`字体「${font.name}」原件超过 32 MB`);
    const bytes = new Uint8Array(await blob.arrayBuffer());
    const current = ensureStorage();
    if (!current) return;
    const saved = await current.preserveImmutable(assetSlot(font.id), {
      version: 1, fontId: font.id, format: font.source.format, base64: encode(bytes),
    });
    if (saved?.reference) originals[font.id] = saved.reference;
  }

  async function restoreOriginals(library, originals, localStore) {
    if (!localStore?.put) return;
    const current = ensureStorage();
    if (!current) return;
    for (const font of library.fonts) {
      if (font.source?.kind !== 'local' || !originals[font.id]) continue;
      if (await localStore.get(font.id)) continue;
      const saved = await current.readImmutable(originals[font.id]);
      const value = saved?.value;
      if (!plain(value) || value.version !== 1 || value.fontId !== font.id
        || value.format !== font.source.format || typeof value.base64 !== 'string') continue;
      const bytes = decode(value.base64);
      await localStore.put(font.id, bytes, 'application/octet-stream');
    }
  }

  async function push(state, { syncLocalOriginals = false, localStore } = {}) {
    const current = ensureStorage();
    if (!current) return { state: normalizeFontLibrary(state), synced: false };
    const previous = await readCatalog();
    const originals = { ...(previous.value?.originals || {}) };
    const library = normalizeFontLibrary(state);
    if (syncLocalOriginals) {
      for (const font of library.fonts) await preserveOriginal(font, localStore, originals);
    }
    const value = { version: FONT_ACCOUNT_SYNC_VERSION, library: stateWithoutPreference(library), originals };
    await writeCatalog(value, previous.fingerprint);
    return { state: library, synced: true };
  }

  async function hydrate(localState, { syncLocalOriginals = false, localStore } = {}) {
    const local = normalizeFontLibrary(localState);
    const current = ensureStorage();
    if (!current) return { state: local, changed: false, synced: false };
    const remote = await readCatalog();
    if (!remote.value) {
      await push(local, { syncLocalOriginals, localStore });
      return { state: local, changed: false, synced: true };
    }
    const merged = mergeFontLibraryRecords(remote.value.library, local.fonts, uniqueId).state;
    const state = normalizeFontLibrary({ ...merged, syncLocalOriginals: local.syncLocalOriginals === true });
    const changed = JSON.stringify(stateWithoutPreference(state)) !== JSON.stringify(remote.value.library);
    if (changed) await writeCatalog({ version: FONT_ACCOUNT_SYNC_VERSION, library: stateWithoutPreference(state), originals: remote.value.originals }, remote.fingerprint);
    fingerprint = fingerprint || remote.fingerprint;
    if (syncLocalOriginals) {
      await restoreOriginals(state, remote.value.originals, localStore);
      await push(state, { syncLocalOriginals: true, localStore });
    }
    return { state, changed, synced: true };
  }

  return Object.freeze({ hydrate, push, close() { storage?.close?.(); storage = null; } });
}

